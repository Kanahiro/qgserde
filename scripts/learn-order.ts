// Generate src/order.generated.ts: the order QGIS writes `<maplayer>` children
// in, by layer type, learned from the QGIS-written fixtures.
// Only `<maplayer>` itself: its children are a fixed set of settings. Deeper
// elements can hold collections whose order is data (form items), so their
// writers own their order. Usage: node scripts/learn-order.ts
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import type { XmlElement } from "../src/types.ts";
import { findChild, findChildren, readXml } from "../src/xml.ts";

const dir = new URL("../test/fixtures/", import.meta.url);
type Sample = { list: string[]; version: number };
const sequences = new Map<string, Sample[]>();
let version = 0;

// A name that reappears after other names is a distinct position (`name@2`).
function tokens(element: XmlElement): string[] {
  const result: string[] = [];
  const seen = new Map<string, number>();
  let previous: string | undefined;
  for (const child of findChildren(element)) {
    if (child.name === previous) continue;
    previous = child.name;
    const count = (seen.get(child.name) ?? 0) + 1;
    seen.set(child.name, count);
    result.push(count === 1 ? child.name : `${child.name}@${count}`);
  }
  return result;
}

function collect(element: XmlElement, key: string): void {
  const list = tokens(element);
  if (list.length > 1)
    sequences.set(key, [...(sequences.get(key) ?? []), { list, version }]);
}

for (const file of readdirSync(dir).filter((name) => name.endsWith(".qgs"))) {
  const root = readXml(readFileSync(new URL(file, dir), "utf8")).root;
  const [major = 0, minor = 0] = (root.attributes.version ?? "")
    .split(/[.-]/u)
    .map(Number);
  version = major * 1000 + minor;
  const container = findChild(root, "projectlayers");
  for (const layer of container ? findChildren(container, "maplayer") : [])
    collect(layer, layer.attributes.type?.toLowerCase() ?? "");
}

// Precedence edges from the newest QGIS version first (targets follow current
// writers); an older edge is kept only when it does not contradict newer ones.
function merge(samples: Sample[]): string[] {
  const names: string[] = [];
  const edges: { from: string; to: string; version: number }[] = [];
  for (const { list, version } of samples)
    for (const [i, from] of list.entries()) {
      if (!names.includes(from)) names.push(from);
      for (const to of list.slice(i + 1)) edges.push({ from, to, version });
    }
  const after = new Map<string, Set<string>>(names.map((n) => [n, new Set()]));
  const reaches = (from: string, to: string): boolean => {
    const stack = [from];
    const seen = new Set(stack);
    for (let name = stack.pop(); name !== undefined; name = stack.pop()) {
      if (name === to) return true;
      for (const next of after.get(name) ?? [])
        if (!seen.has(next)) {
          seen.add(next);
          stack.push(next);
        }
    }
    return false;
  };
  for (const { from, to } of edges.sort((a, b) => b.version - a.version))
    if (!reaches(to, from)) after.get(from)?.add(to);
  const result: string[] = [];
  const rest = new Set(names);
  while (rest.size) {
    const next = [...rest].find(
      (name) => ![...rest].some((other) => after.get(other)?.has(name)),
    );
    if (next === undefined) throw new Error("cyclic order");
    result.push(next);
    rest.delete(next);
  }
  return result.map((token) => token.replace(/@\d+$/u, ""));
}

const table = Object.fromEntries(
  [...sequences]
    .map(([key, samples]) => [key, merge(samples)] as const)
    .filter(([, order]) => new Set(order).size > 1)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
);
writeFileSync(
  new URL("../src/order.generated.ts", import.meta.url),
  `// Generated by scripts/learn-order.ts from QGIS-written fixtures. Do not edit.
/** \`<maplayer>\` child order QGIS writes, by layer type. */
export const layerOrder: Record<string, readonly string[]> = ${JSON.stringify(table, null, 2)};
`,
);
